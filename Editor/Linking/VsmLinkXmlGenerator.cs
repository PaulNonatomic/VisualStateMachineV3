using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Nonatomic.VSM.Attributes;
using Nonatomic.VSM.Core;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEditor.Compilation;
using UnityEditor.UnityLinker;
using UnityEngine;

namespace Nonatomic.VSM.Editor.Linking
{
	/// <summary>
	/// Generates a link.xml at build time that preserves every concrete <see cref="State"/>
	/// subclass and every [BlackboardType] type in the project's player assemblies — including
	/// the consuming project's own.
	///
	/// VSM instantiates states (Activator.CreateInstance) and blackboard handlers by reflection
	/// from assembly-qualified names stored in graph assets. Those references are invisible to
	/// the managed linker, so under IL2CPP Managed Stripping (Medium/High) user-defined states
	/// and blackboard types would be stripped and fail at runtime. This makes them survive with
	/// no action required from the consumer.
	///
	/// Complements the static Runtime/link.xml (which preserves VSM's own assemblies wholesale):
	/// this additionally covers types in user assemblies. Only relevant to IL2CPP builds; the
	/// managed linker doesn't run for the Mono backend.
	/// </summary>
	public class VsmLinkXmlGenerator : IUnityLinkerProcessor
	{
		public int callbackOrder => 0;

		public string GenerateAdditionalLinkXmlFile(BuildReport report, UnityLinkerBuildPipelineData data)
		{
			try
			{
				return GenerateLinkXml();
			}
			catch (Exception ex)
			{
				// Don't fail the consumer's build over a generation hiccup. Degrade to "no
				// auto-preservation" (the static Runtime/link.xml still applies) but make the
				// problem visible — custom states/blackboard types may be stripped.
				Debug.LogError($"[VSM] Failed to generate link.xml; custom state/blackboard types " +
					$"may be stripped under IL2CPP. {ex}");
				return null;
			}
		}

		private static string GenerateLinkXml()
		{
			// Only preserve types from assemblies that are actually part of the player build;
			// referencing editor/test assemblies (which TypeCache also returns) would point the
			// linker at assemblies not present in the build.
			var playerAssemblies = new HashSet<string>(StringComparer.Ordinal);
			foreach (var assembly in CompilationPipeline.GetAssemblies(AssembliesType.Player))
			{
				playerAssemblies.Add(assembly.name);
			}

			var typesByAssembly = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);

			foreach (var stateType in TypeCache.GetTypesDerivedFrom<State>())
			{
				CollectType(stateType, playerAssemblies, typesByAssembly);
			}

			foreach (var blackboardType in TypeCache.GetTypesWithAttribute<BlackboardTypeAttribute>())
			{
				CollectType(blackboardType, playerAssemblies, typesByAssembly);
			}

			var sb = new StringBuilder();
			sb.AppendLine("<!--");
			sb.AppendLine("\tAuto-generated by VSM (VsmLinkXmlGenerator) at build time. Preserves every State");
			sb.AppendLine("\tsubclass and [BlackboardType] type so they survive IL2CPP managed stripping.");
			sb.AppendLine("\tRegenerated on every build; not intended to be edited or committed.");
			sb.AppendLine("-->");
			sb.AppendLine("<linker>");
			foreach (var assembly in typesByAssembly)
			{
				sb.AppendLine($"\t<assembly fullname=\"{Escape(assembly.Key)}\">");
				foreach (var typeName in assembly.Value)
				{
					sb.AppendLine($"\t\t<type fullname=\"{Escape(typeName)}\" preserve=\"all\" />");
				}
				sb.AppendLine("\t</assembly>");
			}
			sb.AppendLine("</linker>");

			var directory = Path.GetFullPath(Path.Combine("Temp", "VSM"));
			Directory.CreateDirectory(directory);
			var filePath = Path.Combine(directory, "VSM.GeneratedLink.xml");
			File.WriteAllText(filePath, sb.ToString());
			return filePath;
		}

		private static void CollectType(
			Type type,
			HashSet<string> playerAssemblies,
			IDictionary<string, SortedSet<string>> typesByAssembly)
		{
			if (type == null || type.IsAbstract || type.IsGenericTypeDefinition) return;

			var typeName = type.FullName;
			if (string.IsNullOrEmpty(typeName)) return;

			var assemblyName = type.Assembly.GetName().Name;
			if (string.IsNullOrEmpty(assemblyName) || !playerAssemblies.Contains(assemblyName)) return;

			if (!typesByAssembly.TryGetValue(assemblyName, out var set))
			{
				set = new SortedSet<string>(StringComparer.Ordinal);
				typesByAssembly[assemblyName] = set;
			}

			set.Add(typeName);
		}

		private static string Escape(string value)
		{
			return value
				.Replace("&", "&amp;")
				.Replace("<", "&lt;")
				.Replace(">", "&gt;")
				.Replace("\"", "&quot;");
		}
	}
}
